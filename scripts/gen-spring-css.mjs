// scripts/gen-spring-css.mjs — generate the CSS `linear()` springs in
// components/ui-system/foundations/tokens.css from the presets in
// components/ui-system/motion/presets.ts, so CSS-only transitions (Tabs
// indicator, Segmented, Button press, Dialog via tw-animate) share the
// framer springs' feel with no JS.
//
// The curves are sampled from motion-dom's own spring generator (the engine
// behind framer-motion), so the CSS and JS springs cannot drift apart:
// change a preset, re-run this script, commit both files.
//
// Usage:
//   node scripts/gen-spring-css.mjs          rewrite the tokens.css block
//   node scripts/gen-spring-css.mjs --check  exit 1 if the block is stale
// `tokens.test.ts` runs --check, so vitest enforces the pin.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGeneratorEasing, generateLinearEasing, spring } from 'motion-dom';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PRESETS = path.join(root, 'components/ui-system/motion/presets.ts');
const TOKENS = path.join(root, 'components/ui-system/foundations/tokens.css');

const START = '/* ── Motion springs (generated by scripts/gen-spring-css.mjs — do not edit) ── */';
const END = '/* ── end generated motion springs ── */';

/** The SPRING table entries: `name: spring(visualDuration, bounce)`. */
function readPresets() {
  const text = readFileSync(PRESETS, 'utf8');
  const entries = [...text.matchAll(/(\w+): spring\(([\d.]+),\s*([\d.]+)\)/g)]
    .map(m => ({ name: m[1], visualDuration: Number(m[2]), bounce: Number(m[3]) }));
  if (entries.length === 0) throw new Error('no spring() entries found in presets.ts');
  return entries;
}

function springCss({ name, visualDuration, bounce }) {
  const generated = createGeneratorEasing(
    { type: 'spring', visualDuration, bounce, keyframes: [0, 1] },
    1,
    spring,
  );
  const ms = Math.round(generated.duration * 1000);
  const curve = generateLinearEasing(generated.ease, ms);
  return { name, ms, curve };
}

function buildBlock(joiner = '\n') {
  const lines = [START];
  for (const preset of readPresets()) {
    const { name, ms, curve } = springCss(preset);
    lines.push(`  --mo-spring-${name}: ${curve};`);
    lines.push(`  --mo-spring-${name}-duration: ${ms}ms;`);
  }
  lines.push(`  ${END}`);
  return lines.join(joiner);
}

function currentBlock() {
  const text = readFileSync(TOKENS, 'utf8');
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start < 0 || end < 0) throw new Error('generated spring block markers not found in tokens.css');
  return text.slice(start, end + END.length);
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  // The block takes the file's own line endings, so --check agrees on Windows (CRLF) and Linux (LF) checkouts alike.
  const text = readFileSync(TOKENS, 'utf8');
  const fresh = buildBlock(text.includes('\r\n') ? '\r\n' : '\n');
  if (process.argv.includes('--check')) {
    if (currentBlock() !== fresh) {
      console.error('tokens.css spring block is stale. Run `node scripts/gen-spring-css.mjs` and commit the result.');
      process.exit(1);
    }
    console.log('spring CSS is current.');
  } else {
    const start = text.indexOf(START);
    const end = text.indexOf(END);
    if (start < 0 || end < 0) throw new Error('generated spring block markers not found in tokens.css');
    writeFileSync(TOKENS, text.slice(0, start) + fresh + text.slice(end + END.length));
    console.log('tokens.css spring block regenerated.');
  }
}
